# core/constants.py
from enum import IntEnum

__all__ = ['NoteName', 'Interval', 'Direction', 'SYNONYMS', 'PAUSE', 'END_OF_SENTENCE']

# --- 1. Абсолютный алфавит (Частоты не привязаны к буквам, но для людей нужны имена) ---
class NoteName(IntEnum):
    DO = 0
    RE = 1
    MI = 2
    FA = 3
    SOL = 4
    LA = 5
    SI = 6

    def __str__(self):
        return self.name

# Альтернативные имена (синонимы) для разных культур и систем
# Это просто словари для отображения, они не меняют суть индексов
SYNONYMS = {
    "ENGLISH": {"C": 0, "D": 1, "E": 2, "F": 3, "G": 4, "A": 5, "B": 6},
    "SOLFEGE": {"Do": 0, "Re": 1, "Mi": 2, "Fa": 3, "Sol": 4, "La": 5, "Si": 6},
    "GERMAN": {"C": 0, "D": 1, "E": 2, "F": 3, "G": 4, "A": 5, "H": 6}
}

# --- 2. Интервалы (Сердце языка) ---
# Измеряются в полутонах. Это абсолютная физическая истина.
class Interval(IntEnum):
    UNISON = 0  # 0 полутонов. Одна и та же нота. "Я", "Да", "Подтверждение"
    MINOR_SECOND = 1  # 1 полутон. Самое близкое расстояние. "Тревога", "Сомнение"
    MAJOR_SECOND = 2  # 2 полутона (1 тон). "Шаг", "Движение", "Идти"
    MINOR_THIRD = 3  # 3 полутона. "Грусть", "Мягкость"
    MAJOR_THIRD = 4  # 4 полутона. "Радость", "Солнце", "Природа"
    PERFECT_FOURTH = 5  # 5 полутонов. "Дом", "Крепость", "Стабильность"
    TRITON = 6  # 6 полутонов (3 тона). "Вопрос", "Напряжение", "Дьявол в музыке"
    PERFECT_FIFTH = 7  # 7 полутонов. "Инструмент", "Машина", "Созданное человеком"
    MINOR_SIXTH = 8  # 8 полутонов. "Внешнее качество", "Холодный"
    MAJOR_SIXTH = 9  # 9 полутонов. "Теплое качество", "Ласковый"
    MINOR_SEVENTH = 10  # 10 полутонов. "Место", "Пространство"
    MAJOR_SEVENTH = 11  # 11 полутонов. "Время", "Изменение"
    OCTAVE = 12  # 12 полутонов. Полный круг. "Бесконечность", "Цикл", "Бог"


# Направление движения — ключ к грамматике
class Direction(IntEnum):
    UP = 1      # Восходящий (свет, добро, активность)
    DOWN = -1   # Нисходящий (тьма, покой, пассивность)
    STATIC = 0  # На месте (прима)

# --- 3. Специальные музыкальные "буквы" ---
# Это не ноты, а элементы ритма и динамики
PAUSE = "⏸"           # Символ паузы
END_OF_SENTENCE = "⏹" # Символ конца предложения (двойная пауза)